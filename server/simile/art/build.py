import json
from pathlib import Path
from typing import Any

from simile.art import characters, preview, tiles
from simile.art.characters import PLAYER, SAMPLES
from simile.schema import Appearance, Npc

CONTENT_DIR = Path(__file__).resolve().parents[3] / "content"
BUILTIN = {"player": PLAYER, **SAMPLES}


def _write_json(path: Path, data: Any) -> Path:
    path.write_text(json.dumps(data, indent=2) + "\n")
    return path


def _save(image: Any, path: Path) -> Path:
    image.save(path)
    return path


def tile_index(cells: list[tiles.Tile | None]) -> str:
    ids = tiles.tile_ids(cells)
    lines = [
        "# Tile index",
        "",
        "Generated by `uv run simile art`; don't edit by hand. Ids are positions in `tiles.png`",
        f"({tiles.COLUMNS} columns, so id = row × {tiles.COLUMNS} + column) and match `tiles.tsj`.",
        "In a map whose tileset has `firstgid` 1, a tile's gid is its id + 1.",
    ]
    for group in tiles.groups():
        lines += ["", f"## {group.name.capitalize()}", "", "| id | name | collides | above |"]
        lines.append("|---:|---|:---:|:---:|")
        for tile in group.tiles:
            collides = "yes" if tile.collides else ""
            above = "yes" if tile.above else ""
            lines.append(f"| {ids[tile.name]} | `{tile.name}` | {collides} | {above} |")
    return "\n".join(lines) + "\n"


def write_tileset(art: Path) -> list[Path]:
    cells = tiles.layout()
    index = art / "tiles.md"
    index.write_text(tile_index(cells))
    return [
        _save(tiles.tileset_canvas(cells).to_image(), art / "tiles.png"),
        _write_json(art / "tiles.tsj", tiles.tileset_json(cells)),
        index,
    ]


def write_character(
    directory: Path, character_id: str, appearance: Appearance, seed: str | None = None
) -> list[Path]:
    image = f"{character_id}.png"
    return [
        _save(characters.sprite_sheet(appearance, seed).to_image(), directory / image),
        _write_json(directory / f"{character_id}.json", characters.atlas(image)),
    ]


def scene_walkers() -> list[preview.Walker]:
    s = SAMPLES
    return [
        preview.Walker(PLAYER, 13 * 16, 11 * 16, "down"),
        preview.Walker(s["sample_barista"], 14 * 16, 10 * 16, "down"),
        preview.Walker(s["sample_coder"], 21 * 16 + 2, 12 * 16, "left"),
        preview.Walker(s["sample_student"], 8 * 16, 10 * 16, "right", 0),
        preview.Walker(s["sample_courier"], 24 * 16, 4 * 16, "left", 2),
        preview.Walker(s["sample_artist"], 4 * 16, 17 * 16, "up"),
        preview.Walker(s["sample_elder"], 1 * 16 + 8, 12 * 16, "right"),
        preview.Walker(s["sample_runner"], 17 * 16, 17 * 16, "left", 0),
        preview.Walker(s["sample_skater"], 8 * 16, 14 * 16, "down", 2),
        preview.Walker(s["sample_teacher"], 23 * 16, 16 * 16, "up"),
        preview.Walker(s["sample_gardener"], 6 * 16, 14 * 16, "left"),
    ]


def write_previews(directory: Path) -> list[Path]:
    directory.mkdir(parents=True, exist_ok=True)
    cells = tiles.layout()
    by_name = {t.name: t for t in cells if t is not None}
    scene = preview.render_scene(preview.village(), by_name, scene_walkers())
    walk = directory / "walk.gif"
    preview.save_gif(preview.walk_frames(list(BUILTIN.values()), by_name["pavement"]), str(walk))
    return [
        _save(preview.tiles_sheet(cells), directory / "tiles.png"),
        _save(preview.scaled(scene, 3), directory / "scene.png"),
        _save(preview.characters_sheet(BUILTIN), directory / "characters.png"),
        walk,
    ]


def load_npcs(directory: Path) -> dict[str, Appearance]:
    npcs = {}
    for path in sorted(directory.glob("*.json")):
        npc = Npc.model_validate_json(path.read_text())
        if npc.id in BUILTIN:
            raise ValueError(f"{path}: NPC id {npc.id!r} clashes with a built-in sprite")
        npcs[npc.id] = npc.appearance
    return npcs


def generate(content: Path = CONTENT_DIR, npcs_only: bool = False) -> list[Path]:
    """Regenerate content/art/; with npcs_only, just the NPC sprites and their preview."""
    art = content / "art"
    sprites = art / "characters"
    sprites.mkdir(parents=True, exist_ok=True)
    npcs = load_npcs(content / "npcs")
    keep = set(BUILTIN) | set(npcs)
    for path in sprites.iterdir():
        if path.suffix in (".png", ".json") and path.stem not in keep:
            path.unlink()
    written = []
    if not npcs_only:
        written += write_tileset(art)
        for character_id, appearance in BUILTIN.items():
            written += write_character(sprites, character_id, appearance)
        written += write_previews(art / "preview")
    for character_id, appearance in npcs.items():
        written += write_character(sprites, character_id, appearance, seed=character_id)
    npc_preview = art / "preview" / "npcs.png"
    if npcs:
        npc_preview.parent.mkdir(parents=True, exist_ok=True)
        written.append(_save(preview.characters_sheet(npcs, seeded=True), npc_preview))
    elif npc_preview.exists():
        npc_preview.unlink()
    return written
